/**
 * Regenerate `packages/core/src/mod/record-keys.ts` from the shipped pack.
 *
 * WHAT THE TABLE IS. Per record file, every top-level key that core's OWN data
 * uses. That is the right definition of "a key core knows about", and it is
 * DERIVED rather than declared: core's gamedata is what exercises core's
 * parser, so anything outside this set came from somewhere else - a mod. It
 * cannot drift the way a hand-maintained list would, and record-keys.test.ts
 * fails in both directions if it does.
 *
 * WHY NOT READ THE SPEC INSTEAD. `packages/content` holds a FileSpec per file
 * describing the upstream directives, which is a more principled source. Core
 * has ZERO package dependencies on purpose - that standalone-ness is what the
 * layering audit rests on - so importing the spec into core would buy accuracy
 * with a dependency that is not worth it. The generated table is checked
 * against the pack instead, which catches the same drift.
 *
 * A KEY CORE READS BUT NEVER SHIPS is the one imprecision, and it is benign: a
 * mod supplying it gets it BOUND normally by the binder AND listed in `ext`.
 * Duplicated, not lost.
 *
 *   node packages/core/scripts/gen-record-keys.mjs
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const packDir = fileURLToPath(new URL("../../content/pack", import.meta.url));

const table = {};
for (const file of readdirSync(packDir).filter((f) => f.endsWith(".json")).sort()) {
  const stem = file.replace(/\.json$/, "");
  const raw = JSON.parse(readFileSync(`${packDir}/${file}`, "utf8"));
  const records = Array.isArray(raw) ? raw : raw.records;
  if (!Array.isArray(records)) continue;
  const keys = new Set();
  for (const r of records) {
    if (r && typeof r === "object" && !Array.isArray(r)) {
      for (const k of Object.keys(r)) keys.add(k);
    }
  }
  table[stem] = [...keys].sort();
}

const body = Object.entries(table)
  .map(([stem, keys]) => {
    const list = keys.map((k) => JSON.stringify(k)).join(", ");
    return `  ${JSON.stringify(stem)}: [${list}],`;
  })
  .join("\n");

const out = `/**
 * The top-level keys core's own gamedata uses, per record file.
 *
 * GENERATED by scripts/gen-record-keys.mjs from packages/content/pack. Do not
 * edit by hand; record-keys.test.ts re-derives it from the shipped pack and
 * fails in both directions, so an edit here is undone by the next run either
 * way.
 *
 * This exists so a mod can ADD a key. Composition has always carried an
 * unrecognised key through untouched, but every binder then dropped it on the
 * floor - so a mod could write \`"bleed": {...}\` on a dagger, see no error, and
 * find nothing at runtime. Subtracting this table from a record's keys is what
 * separates "core reads this" from "a mod added this", and the leftovers ride
 * along on the bound record as \`ext\`.
 */

/** file stem -> the keys core's data uses, sorted. */
export const CORE_RECORD_KEYS: Readonly<Record<string, readonly string[]>> = {
${body}
};

/**
 * The keys of \`record\` that core does not know about, or undefined when there
 * are none.
 *
 * Undefined rather than an empty object so the overwhelmingly common case - an
 * unmodded record - adds no allocation and no property, and so \`ext\` being
 * present means something.
 *
 * An UNKNOWN FILE yields undefined rather than treating every key as an
 * extension: a file core ships no data for is one this table cannot speak
 * about, and guessing there would hand a mod an \`ext\` full of core's own
 * fields.
 */
export function extensionData(
  file: string,
  record: object,
): Readonly<Record<string, unknown>> | undefined {
  const known = CORE_RECORD_KEYS[file];
  if (known === undefined) return undefined;
  let out: Record<string, unknown> | undefined;
  for (const [key, value] of Object.entries(record)) {
    if (known.includes(key)) continue;
    out ??= {};
    out[key] = value;
  }
  return out === undefined ? undefined : Object.freeze(out);
}
`;

const dest = fileURLToPath(new URL("../src/mod/record-keys.ts", import.meta.url));
writeFileSync(dest, out, "utf8");
console.log(
  `wrote ${String(Object.keys(table).length)} files, ` +
    `${String(new Set(Object.values(table).flat()).size)} distinct keys`,
);
